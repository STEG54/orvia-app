CREATE TABLE IF NOT EXISTS inscriptions (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  conciergerie VARCHAR(120) NOT NULL, ville VARCHAR(80) NOT NULL DEFAULT '', nom VARCHAR(120) NOT NULL, email VARCHAR(160) NOT NULL,
  telephone VARCHAR(30) NOT NULL DEFAULT '', logements SMALLINT UNSIGNED NOT NULL DEFAULT 1,
  pass_hash VARCHAR(255) NOT NULL, jeton_hash CHAR(64) NOT NULL, slug VARCHAR(30) DEFAULT NULL,
  statut VARCHAR(12) NOT NULL DEFAULT 'a_confirmer', erreur VARCHAR(500) NOT NULL DEFAULT '', ip VARCHAR(45) NOT NULL DEFAULT '',
  created_at DATETIME NOT NULL, confirme_at DATETIME DEFAULT NULL, pret_at DATETIME DEFAULT NULL,
  UNIQUE KEY jeton (jeton_hash), KEY statut (statut), KEY email (email), UNIQUE KEY slug (slug)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS inscriptions_essais (ip VARCHAR(45) NOT NULL, t DATETIME NOT NULL, KEY ip (ip, t)) ENGINE=InnoDB;
